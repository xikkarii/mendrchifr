#ifndef MEANDER_H
#define MEANDER_H

#include <vector>
#include <cstdint>
#include <utility>

// ─────────────────────────────────────────────────────────────────────────
//  Генерация замкнутых меандров порядка n
//
//  Меандр порядка n — замкнутая самонепересекающаяся кривая, пересекающая
//  горизонтальную прямую в 2n точках. Кривая задаётся двумя наборами дуг:
//  верхними (над прямой) и нижними (под прямой). Каждый набор образует
//  непересекающееся совершенное паросочетание на 2n точках.
// ─────────────────────────────────────────────────────────────────────────

using Arc = std::pair<int, int>;       // дуга, соединяющая две точки пересечения
using Matching = std::vector<Arc>;     // паросочетание (набор дуг)

// Описание одного меандра.
struct Meander {
    int order = 0;                     // порядок n
    Matching upper;                    // верхние дуги
    Matching lower;                    // нижние дуги (каноническая «радуга»)
    std::vector<int> traversal;        // последовательность обхода точек (перестановка)
};

// Генерирует все замкнутые меандры заданного порядка n (1..10).
// Нижнее паросочетание фиксировано как «радуга»; перебираются все
// непересекающиеся верхние паросочетания, отбираются дающие единый цикл.
std::vector<Meander> generateMeanders(int n);

#endif // MEANDER_H
